def logSubstitutionPyomoCode(logToVariableDict, modelName, staticOrDynamic):
    # Variables for the u variables in the log substitution are instantiated with this function (log(x) = u)
    def addValue(match):
        return match.group(1) + '.value'
    # Pattern to find variables and add to them .value method
    pattern = rf'\b({modelName}\.[a-zA-Z0-9_]+)\b'
    # Empty list to store the Pyomo code for the log substitution variables
    subLogVarsPyomoCode = []
    n = len(logToVariableDict.keys())
    if staticOrDynamic == "Dynamic":
        for i in range(n):
            logArgumentComponents = re.sub(r"\[t\]", f"[{modelName}.time.ordered_data()[0]]",logToVariableDict[i+1])
            stringNominal = (f"varList = list(identify_variables(log({logArgumentComponents})))\n"
                             f"listScaling = []\n"
                             f"for var in varList:\n"
                             f"\tvarName = re.sub(r'\[.*\]', '', str(var))\n"
                             f"\tvarName = \"{modelName}.\" + varName\n"
                             f"\tlistScaling.append(abs(differentiate(log({logArgumentComponents}), wrt=var)/{modelName}.scaling_factor[eval(varName)]))\n"
                             f"{modelName}.scaling_factor[{modelName}.u{i+1}] = 1/max(listScaling)\n")

            logArgument = re.sub(r"\[t\]", r"[m.time.ordered_data()[0]]",logToVariableDict[i+1])
            
            subLogVarsPyomoCode.append(f"{modelName}.u{i+1} = Var(m.time, initialize = log(" + logArgument + f"), within = Reals)\n{stringNominal}")#m.scaling_factor[{modelName}.u{i+1}] = 1\n")
    elif staticOrDynamic == "Static":
        for i in range(n):
            stringNominal = (f"varList = list(identify_variables(log({logToVariableDict[i+1]})))\n"
                             f"listScaling = []\n"
                             f"for var in varList:\n"
                             f"\tvarName = \"{modelName}.\" + str(var)\n"
                             f"\tlistScaling.append(abs(differentiate(log({logToVariableDict[i+1]}), wrt=var)/{modelName}.scaling_factor[eval(varName)]))\n"
                             f"{modelName}.scaling_factor[{modelName}.u{i+1}] = 1/max(listScaling)\n")

            stringInit = re.sub(pattern, addValue, logToVariableDict[i+1])
            subLogVarsPyomoCode.append(f"{modelName}.u{i+1} = Var(initialize = log(" + stringInit + f"), within = Reals)\n{stringNominal}\n")
    
